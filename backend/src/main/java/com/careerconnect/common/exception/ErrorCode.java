package com.careerconnect.common.exception;

public enum ErrorCode {

    // 400 Bad Request
    VALIDATION_FAILED("VALIDATION_FAILED"),

    // 401 Unauthorized
    UNAUTHENTICATED("UNAUTHENTICATED"),
    INVALID_CREDENTIALS("INVALID_CREDENTIALS"),

    // 403 Forbidden
    FORBIDDEN("FORBIDDEN"),

    // 404 Not Found
    RESOURCE_NOT_FOUND("RESOURCE_NOT_FOUND"),
    JOB_NOT_FOUND("JOB_NOT_FOUND"),

    // 409 Conflict
    EMAIL_ALREADY_EXISTS("EMAIL_ALREADY_EXISTS"),
    DUPLICATE_APPLICATION("DUPLICATE_APPLICATION"),
    COMPANY_ALREADY_EXISTS("COMPANY_ALREADY_EXISTS"),

    // 422 Unprocessable Content (Business Rules)
    CANDIDATE_PROFILE_INCOMPLETE("CANDIDATE_PROFILE_INCOMPLETE"),
    CANDIDATE_RESUME_REQUIRED("CANDIDATE_RESUME_REQUIRED"),
    COMPANY_REQUIRED("COMPANY_REQUIRED"),
    JOB_NOT_ACTIVE("JOB_NOT_ACTIVE"),
    JOB_DEADLINE_PASSED("JOB_DEADLINE_PASSED"),
    JOB_DEADLINE_INVALID("JOB_DEADLINE_INVALID"),
    JOB_SKILL_REQUIRED("JOB_SKILL_REQUIRED"),
    INVALID_STATUS_TRANSITION("INVALID_STATUS_TRANSITION"),
    RESUME_INVALID_TYPE("RESUME_INVALID_TYPE"),
    RESUME_TOO_LARGE("RESUME_TOO_LARGE"),

    // 500 Internal Error
    INTERNAL_ERROR("INTERNAL_ERROR");

    private final String code;

    ErrorCode(String code) {
        this.code = code;
    }

    public String getCode() {
        return code;
    }
}
